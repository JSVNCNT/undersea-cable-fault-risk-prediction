it('isolates external loading failures and keeps a link to existing model results', async () => {
  vi.stubEnv('VITE_EXTERNAL_DATA_MODE', 'bundled');
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('', { status: 503 })));
  render(
    <MemoryRouter>
      <ExternalEvidence />
    </MemoryRouter>,
  );
  expect(await screen.findByRole('alert')).toHaveProperty(
    'textContent',
    expect.stringContaining('503'),
  );
  expect(
    screen.getByRole('link', { name: 'View existing model results' }).getAttribute('href'),
  ).toBe('/models');
  expect(screen.getByRole('button', { name: 'Retry external evidence' })).toBeTruthy();
});

it('keeps the external route functional when the original synthetic release fails and never exports the wrong snapshot', async () => {
  vi.stubGlobal('scrollTo', vi.fn()); // jsdom has no visual scrolling implementation.
  vi.mocked(loadData).mockRejectedValue(new Error('Original release unavailable in this fixture'));
  vi.stubEnv('VITE_EXTERNAL_DATA_MODE', 'bundled');
  vi.stubGlobal(
    'fetch',
    vi
      .fn()
      .mockResolvedValue(
        new Response(
          JSON.stringify(JSON.parse(readFileSync('public/external-data/research.json', 'utf8'))),
        ),
      ),
  );
  render(
    <MemoryRouter initialEntries={['/external']}>
      <App />
    </MemoryRouter>,
  );
  expect(
    await screen.findByRole('heading', { name: 'Infrastructure and maritime exposure' }),
  ).toBeTruthy();
  expect(screen.queryByRole('button', { name: 'Export snapshot' })).toBeNull();
  expect(
    screen.getByRole('link', { name: 'Download evidence snapshot' }).getAttribute('href'),
  ).toBe('/external-data/research.json');
  expect(screen.getByText('Independent external release')).toBeTruthy();
  expect(loadData).not.toHaveBeenCalled();
  expect(screen.queryByRole('heading', { name: 'Research data unavailable' })).toBeNull();
});
